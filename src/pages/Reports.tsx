function buildReportPDF(tab: ReportTab, user: UserProfile): ArrayBuffer {
  const date = new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })
  const clean = (value: string) => value.replace(/[^\x20-\x7E]/g, '').replace(/([\\()])/g, '\\$1')
  const lines = [
    REPORT_LABELS[tab],
    `Student: ${user.name}`,
    `Grade or course: ${user.grade}`,
    `Generated: ${date}`,
    '',
    'Available progress data',
    `Overall understanding: ${user.understanding}%`,
    `Lessons completed: ${user.lessonsCompleted}`,
    `Current streak: ${user.streak} days`,
    '',
    'Learning preferences',
    `Visual materials preference: ${user.learningPattern.visual}%`,
    `Audio materials preference: ${user.learningPattern.audio}%`,
    `Examples preference: ${user.learningPattern.examples}%`,
    `Step-by-step preference: ${user.learningPattern.stepByStep}%`,
    '',
    'Reading and accessibility settings',
    `Font: ${user.accessibility.fontFamily}`,
    `Text size: ${user.accessibility.fontSize}`,
    `Line spacing: ${user.accessibility.lineSpacing}`,
    `Audio support: ${user.accessibility.audioEnabled ? 'Enabled' : 'Disabled'}`,
    '',
    'Data note',
    'This report contains locally available profile data.',
    'Topic examples shown in the application may be sample data.',
  ]
  const content = lines.map((line, index) => {
    const y = 800 - index * 27
    const size = index === 0 ? 18 : index === 5 || index === 10 || index === 16 || index === 22 ? 13 : 10
    return `BT /F1 ${size} Tf 54 ${y} Td (${clean(line)}) Tj ET`
  }).join('\n')

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${new TextEncoder().encode(content).length} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ]
  let pdf = '%PDF-1.4\n'
  const offsets = [0]
  objects.forEach((object, index) => {
    offsets.push(new TextEncoder().encode(pdf).length)
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`
  })
  const xrefOffset = new TextEncoder().encode(pdf).length
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
  offsets.slice(1).forEach(offset => { pdf += `${String(offset).padStart(10, '0')} 00000 n \n` })
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`
  return new TextEncoder().encode(pdf).buffer as ArrayBuffer
}

function ExportButton({ tab, user, exportState, setExportState }: {
  tab: ReportTab
  user: UserProfile
  exportState: ExportState
  setExportState: (s: ExportState) => void
}) {
  const downloadHTML = () => {
    const html = buildReportHTML(tab, user)
    const blob = new Blob([html], { type: 'text/html' })
    const url = URL.createObjectURL(blob)
    const anchor = document.createElement('a')
    anchor.href = url
    anchor.download = `LearnTwin_${REPORT_LABELS[tab].replace(/ /g, '_')}_${user.name}.html`
    document.body.appendChild(anchor)
    anchor.click()
    document.body.removeChild(anchor)
    URL.revokeObjectURL(url)
  }

  const startExport = () => {
    setExportState('preparing')
    setTimeout(() => setExportState('generating'), 1400)
    setTimeout(() => setExportState('ready'), 2800)
  }

  const download = () => {
    const pdf = buildReportPDF(tab, user)
    const blob = new Blob([pdf], { type: 'application/pdf' })
    const url  = URL.createObjectURL(blob)
    const a    = document.createElement('a')
    a.href     = url
    a.download = `LearnTwin_${REPORT_LABELS[tab].replace(/ /g, '_')}_${user.name}.pdf`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
    setTimeout(() => setExportState('idle'), 1500)
  }

  if (exportState === 'idle') {
    return (
      <div className="flex items-center gap-2 flex-shrink-0">
        <button onClick={downloadHTML} className="px-3 py-2 rounded-xl font-bold text-xs border" style={{ background: 'var(--card)', borderColor: 'var(--border)', color: 'var(--muted-foreground)' }}>
          HTML
        </button>
        <button
          onClick={startExport}
          className="flex items-center gap-1.5 px-3 py-2 rounded-xl font-bold text-xs btn-press shadow-sm"
          style={{ background: 'var(--primary)', color: 'var(--primary-foreground)' }}
        >
          <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"/><polyline points="7 10 12 15 17 10"/><line x1="12" y1="15" x2="12" y2="3"/></svg>
          Export PDF
        </button>
      </div>
    )
  }
  if (exportState === 'preparing' || exportState === 'generating') {
    return (
      <div className="flex items-center gap-2 px-3 py-2 rounded-xl text-xs font-bold flex-shrink-0" style={{ background: 'var(--muted)', color: 'var(--muted-foreground)' }}>
        <div className="w-3 h-3 border-2 rounded-full animate-spin" style={{ borderColor: 'rgba(15,118,110,.3)', borderTopColor: 'var(--primary)' }} />
        {exportState === 'preparing' ? 'Preparing…' : 'Generating…'}
      </div>
    )
  }
  return (
    <button
      onClick={download}
      className="flex items-center gap-1.5 px-3 py-2 rounded-xl font-bold text-xs btn-press shadow-sm flex-shrink-0 animate-pop"
      style={{ background: '#10B981', color: '#fff' }}
    >
      ✅ Download PDF
    </button>
  )
}

